create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id text not null,
  name text not null,
  description text not null default '',
  emoji text not null default '🍰',
  image_url text,
  tag text,
  sizes jsonb,
  price numeric(10, 2),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint products_price_or_sizes check (
    (price is not null and price > 0 and sizes is null)
    or (price is null and sizes is not null and jsonb_typeof(sizes) = 'array')
  )
);

create table if not exists public.store_settings (
  id integer primary key check (id = 1),
  hero_visible boolean not null default true,
  hero_image_visible boolean not null default true,
  hero_title text not null default 'Bolos que tornam',
  hero_emphasis text not null default 'momentos',
  hero_ending text not null default 'inesquecíveis',
  hero_subtitle text not null default '',
  hero_image_url text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.store_settings enable row level security;

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_store_admin() from public, anon;
grant execute on function public.is_store_admin() to authenticated;

grant select on public.products, public.store_settings to anon, authenticated;
grant select on public.admin_users to authenticated;
grant insert, update, delete on public.products to authenticated;
grant insert, update on public.store_settings to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists "Admins can read their own membership" on public.admin_users;
create policy "Admins can read their own membership"
  on public.admin_users for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select to anon, authenticated
  using (is_active);

drop policy if exists "Admins can read all products" on public.products;
create policy "Admins can read all products"
  on public.products for select to authenticated
  using ((select public.is_store_admin()));

drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
  on public.products for insert to authenticated
  with check ((select public.is_store_admin()));

drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
  on public.products for update to authenticated
  using ((select public.is_store_admin()))
  with check ((select public.is_store_admin()));

drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
  on public.products for delete to authenticated
  using ((select public.is_store_admin()));

drop policy if exists "Public can read store settings" on public.store_settings;
create policy "Public can read store settings"
  on public.store_settings for select to anon, authenticated
  using (true);

drop policy if exists "Admins can insert store settings" on public.store_settings;
create policy "Admins can insert store settings"
  on public.store_settings for insert to authenticated
  with check ((select public.is_store_admin()));

drop policy if exists "Admins can update store settings" on public.store_settings;
create policy "Admins can update store settings"
  on public.store_settings for update to authenticated
  using ((select public.is_store_admin()))
  with check ((select public.is_store_admin()));

